function loadFallback() {
  const upsert = db.prepare(`
    INSERT INTO seeds(
      external_id, name, category, sun, water, sow_time, bloom_time,
      row_spacing_cm, sow_depth_cm, mature_height_cm, source_url,
      water_interval_days, harvest_days_min, harvest_days_max, icons_json
    ) VALUES (
      @external_id, @name, @category, @sun, @water, @sow_time, @bloom_time,
      @row_spacing_cm, @sow_depth_cm, @mature_height_cm, @source_url,
      @water_interval_days, @harvest_days_min, @harvest_days_max, @icons_json
    )
    ON CONFLICT(external_id) DO UPDATE SET
      name=excluded.name,
      sun=excluded.sun,
      water=excluded.water,
      sow_time=excluded.sow_time,
      bloom_time=excluded.bloom_time,
      row_spacing_cm=excluded.row_spacing_cm,
      sow_depth_cm=excluded.sow_depth_cm,
      mature_height_cm=excluded.mature_height_cm,
      water_interval_days=excluded.water_interval_days,
      harvest_days_min=excluded.harvest_days_min,
      harvest_days_max=excluded.harvest_days_max,
      updated_at=datetime('now')
  `);

  const tx = db.transaction((items) => {
    for (const item of items) {
      upsert.run({
        ...item,
        water_interval_days: waterIntervalFromText(item.water, 3),
        icons_json: JSON.stringify([
          { label: item.sun, kind: 'sun' },
          { label: item.water, kind: 'water' },
        ]),
      });
    }
  });
  tx(FALLBACK);
  console.log(`Fallback catalog: ${FALLBACK.length} seeds`);
}

module.exports = { loadFallback, FALLBACK };

if (require.main === module) loadFallback();
